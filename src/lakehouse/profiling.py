"""Profile every bronze dataset and reconcile it with what the ingest read from the source files.

For each dataset: row count, per-column null count / min / max / approximate distinct count, and the number of
duplicate keys. Reconciliation (the post-load validation step of a migration): bronze row counts and volume sums
must equal the valid rows and sums counted while reading the source.
"""
from __future__ import annotations

import json
from pathlib import Path

from .batch_ingest import PV_OD, PV_STOP
from .storage import Lake, duckdb_connect

DATASETS = {
    "speedbands": ("snapshot_ts", "link_id"),
    "speedband_links": ("LinkID",),
    "pv_stop": PV_STOP.key,
    "pv_od": PV_OD.key,
    "bus_stops": ("as_of", "BusStopCode"),
    "bus_services": ("as_of", "ServiceNo", "Direction"),
    "bus_routes": ("as_of", "ServiceNo", "Direction", "StopSequence"),
}


def profile_dataset(con, lake: Lake, name: str, key: tuple) -> dict | None:
    files = lake.list_files(f"bronze/{name}")
    if not files:
        return None
    src = f"read_parquet('{lake.uri(f'bronze/{name}')}/**/*.parquet', hive_partitioning = true, union_by_name = true)"
    con.execute(f"CREATE OR REPLACE TEMP VIEW p AS SELECT * FROM {src}")
    cols = [r[0] for r in con.execute("DESCRIBE p").fetchall()]
    n = con.execute("SELECT count(*) FROM p").fetchone()[0]
    stats = {}
    for c in cols:
        nulls, lo, hi, nd = con.execute(
            f'SELECT count(*) - count("{c}"), min("{c}")::VARCHAR, max("{c}")::VARCHAR, '
            f'approx_count_distinct("{c}") FROM p').fetchone()
        stats[c] = {"nulls": nulls, "min": lo, "max": hi, "approx_distinct": nd}
    k = ", ".join(f'"{c}"' for c in key)
    dup = con.execute(f"SELECT count(*) FROM (SELECT {k} FROM p GROUP BY {k} HAVING count(*) > 1)").fetchone()[0]
    return {"dataset": name, "files": len(files), "rows": n, "key": list(key), "duplicate_keys": dup, "columns": stats}


def reconcile(con, lake: Lake, loads: list[dict]) -> list[dict]:
    out = []
    for x in loads:
        if x["dataset"] not in ("pv_stop", "pv_od"):
            continue
        src = f"read_parquet('{lake.uri(x['bronze_path'])}/*.parquet')"
        cols = list(x["valid_sums"])
        row = con.execute(f"SELECT count(*), {', '.join(f'sum({c})' for c in cols)} FROM {src}").fetchone()
        sums = dict(zip(cols, [int(v) if v is not None else None for v in row[1:]]))
        out.append({"dataset": x["dataset"], "file": x["file"], "source_valid_rows": x["rows_valid"],
                    "bronze_rows": row[0], "source_sums": x["valid_sums"], "bronze_sums": sums,
                    "match": row[0] == x["rows_valid"] and sums == x["valid_sums"]})
    return out


def run(settings) -> dict:
    lake = Lake(settings)
    con = duckdb_connect(settings)
    prof = [p for name, key in DATASETS.items() if (p := profile_dataset(con, lake, name, key))]
    ingest = Path(settings.results_dir) / "batch_ingest.json"
    rec = reconcile(con, lake, json.loads(ingest.read_text(encoding="utf-8"))["loads"]) if ingest.exists() else []
    con.close()
    report = {"datasets": prof, "reconciliation": rec, "all_reconciled": all(r["match"] for r in rec) and bool(rec)}
    out = Path(settings.results_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "profile_bronze.json").write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
    (out / "profile_bronze.md").write_text(to_markdown(report), encoding="utf-8")
    return report


def to_markdown(report) -> str:
    lines = ["# Bronze profile", "", "Generated by `python -m lakehouse profile`.", "",
             "| Dataset | Files | Rows | Key | Duplicate keys |", "|---|---|---|---|---|"]
    for d in report["datasets"]:
        lines.append(f"| {d['dataset']} | {d['files']} | {d['rows']:,} | {', '.join(d['key'])} | {d['duplicate_keys']} |")
    lines += ["", "## Source-to-bronze reconciliation", "",
              "| File | Source valid rows | Bronze rows | Sums match | Match |", "|---|---|---|---|---|"]
    for r in report["reconciliation"]:
        lines.append(f"| {r['file']} | {r['source_valid_rows']:,} | {r['bronze_rows']:,} | "
                     f"{r['source_sums'] == r['bronze_sums']} | {r['match']} |")
    for d in report["datasets"]:
        lines += ["", f"## {d['dataset']}", "", "| Column | Nulls | Min | Max | Approx. distinct |",
                  "|---|---|---|---|---|"]
        for c, s in d["columns"].items():
            lines.append(f"| {c} | {s['nulls']:,} | {s['min']} | {s['max']} | {s['approx_distinct']:,} |")
    return "\n".join(lines) + "\n"
