"""Build results/SUMMARY.md from the results files, and keep the README's results block identical to it.

Every number in the README's "Measured results" section comes from this generator, so it cannot drift from the
files the pipeline wrote. `--check` (run in CI) fails if README.md and the results files disagree.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from .config import REPO

START, END = "<!-- results:start -->", "<!-- results:end -->"


def _load(res: Path, name: str):
    p = res / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _n(x) -> str:
    return f"{x:,}" if isinstance(x, int) else str(x)


def _s(ms) -> str:
    return f"{ms / 1000:.1f} s"


def build(res: Path) -> str:
    out = ["_Generated by `python -m lakehouse summarize` from the files in `results/`; do not edit by hand._", ""]
    files = _load(res, "speedband_files.json")
    loads = _load(res, "batch_ingest.json")
    if files and loads:
        snaps = files["snapshots"]
        rows = sorted({s["rows_in"] for s in snaps})
        out += ["### Inputs", "",
                f"- {len(snaps)} speed-band snapshots from {snaps[0]['snapshot_ts'].replace('T', ' ')} to "
                f"{snaps[-1]['snapshot_ts'].replace('T', ' ')} (SGT), {' to '.join(_n(r) for r in rows)} links each, "
                f"{_n(sum(s['rows_in'] for s in snaps))} rows in total.",
                ]
        for ds, label in (("pv_stop", "Stop tap-in/tap-out files"), ("pv_od", "Origin-destination files")):
            ls = [x for x in loads["loads"] if x["dataset"] == ds]
            if ls:
                out.append(f"- {label}: {', '.join(x['year_month'] for x in ls)}; "
                           f"{_n(sum(x['rows_read'] for x in ls))} rows read, "
                           f"{_n(sum(x['rows_quarantined'] for x in ls))} quarantined.")
        out.append("")

    sb = _load(res, "stream_benchmark.json")
    if sb:
        t, lat, rr = sb["throughput"], sb["latency"], sb["rerun"]
        out += ["### Streaming (Redpanda -> consumers -> MinIO bronze)", "",
                f"{sb['snapshots']} snapshots, {t['consumers']} consumer processes (one per partition), "
                f"measured by `python -m lakehouse stream-bench`.", "",
                "| Run | Messages produced | Producer msg/s | Consumer records/s | Latency p50 | p95 | max |",
                "|---|---|---|---|---|---|---|"]
        for name, r in (("throughput (unpaced, 1% duplicates, 2 late snapshots)", t),
                        (f"latency (paced x{lat['speedup']:g})", lat), ("re-run of the same data", rr)):
            c = r["consumer"]
            rate = "paced" if r is lat else _n(c["records_per_s"])
            out.append(f"| {name} | {_n(r['producer']['messages'])} | {_n(r['producer']['msgs_per_s'])} | "
                       f"{rate} | {_s(c['latency_ms']['p50'])} | {_s(c['latency_ms']['p95'])} | "
                       f"{_s(c['latency_ms']['max'])} |")
        tc = t["consumer"]
        out += ["",
                f"- Latency is from the producer's timestamp on a record to the moment its bronze object was written "
                f"to MinIO. In the unpaced runs the producer outruns the consumers, so latency there is mostly "
                f"queueing; the paced run is the meaningful one. There the producer takes "
                f"{lat['producer']['send_seconds'] / lat['producer']['snapshots']:.1f} s to send one snapshot, and "
                f"a bronze object is written only when its partition's end-of-snapshot marker arrives, so most of "
                f"the latency is waiting for the rest of the snapshot.",
                f"- Messages include {_n(t['producer']['snapshots'] * t['consumers'])} end-of-snapshot markers "
                f"(one per snapshot and partition); consumer rates count link records only.",
                f"- Duplicates: {_n(t['producer']['duplicates_injected'])} injected, "
                f"{_n(tc['duplicates_dropped'])} dropped by the consumers; bronze holds "
                f"{_n(tc['rows_new_in_bronze'])} rows = {sb['snapshots']} snapshots x links, no duplicate key.",
                f"- Late data: {len(tc['snapshots_late'])} snapshots held back and sent last were flagged late "
                f"({', '.join(x.replace('T', ' ') for x in tc['snapshots_late'])}) and written to their own "
                f"event-time partitions; {tc['flushes_incomplete']} incomplete flushes.",
                f"- Re-run: {_n(rr['consumer']['records_consumed'])} records consumed again, "
                f"{_n(rr['consumer']['rows_new_in_bronze'])} new rows, {rr['consumer']['objects_written']} objects "
                f"rewritten; all {rr['bronze_objects']} bronze objects kept the same SHA-256: "
                f"{'yes' if rr['bronze_unchanged'] else 'NO'}.",
                ""]

    lc = _load(res, "layer_counts.json")
    if lc:
        out += ["### Rows per layer", "", "| Layer | Table | Rows |", "|---|---|---|"]
        for layer in ("bronze", "silver", "gold"):
            for k, v in lc[layer].items():
                rows = v["rows"] if isinstance(v, dict) else v
                extra = (f" ({_n(v['files'])} file{'s' if v['files'] != 1 else ''})"
                         if isinstance(v, dict) else "")
                out.append(f"| {layer} | {k}{extra} | {_n(rows)} |")
        out.append("")

    prof = _load(res, "profile_bronze.json")
    if prof:
        rec = prof["reconciliation"]
        dups = {d["dataset"]: d["duplicate_keys"] for d in prof["datasets"]}
        out += ["### Load validation", "",
                f"- Source-to-bronze reconciliation (row counts and volume sums): "
                f"{sum(r['match'] for r in rec)}/{len(rec)} files match.",
                "- Duplicate keys in bronze: " + ", ".join(f"{k} {v}" for k, v in dups.items()) + ".", ""]

    q = _load(res, "quality_report.json")
    if q:
        c = {x["check"]: x for x in q["checks"]}
        out += ["### Data-quality findings", "", "| Check | Status | Value | Threshold |", "|---|---|---|---|"]
        for x in q["checks"]:
            thr = x["threshold"]
            if isinstance(thr, dict):
                thr = ", ".join(f"{k} {v}" for k, v in thr.items())
            out.append(f"| {x['check']} | {x['status']} | {x['value']} | {thr} |")
        out.append("")
        cad = c["cadence_gap"]["details"]
        if cad.get("regular_minutes_min_median_max"):
            lo, med, hi = cad["regular_minutes_min_median_max"]
            out.append(f"- Sampling cadence: {cad['regular_intervals']} of {cad['intervals']} intervals were "
                       f"regular ({lo}-{hi} min, median {med} min).")
        for g in cad["long_gaps"]:
            out.append(f"- Gap of {g['minutes']:,.0f} min from {g['from'].replace('T', ' ')} to "
                       f"{g['to'].replace('T', ' ')}: no snapshots.")
        for g in cad["short_gaps"]:
            out.append(f"- Only {g['minutes']:g} min between {g['from'].replace('T', ' ')} and "
                       f"{g['to'].replace('T', ' ')}.")
        sl = c["sampler_log_consistency"]["details"]
        out.append(f"- sampler.log had {sl['log_fetch_lines']} fetch lines for {sl['snapshot_files']} snapshot files "
                   f"when the check ran (all files in the folder, not only those up to the cutoff; the sampler was "
                   f"still running). Every line reports {', '.join(_n(x) for x in sl['row_counts_in_log'])} rows. "
                   f"The log has {'' if sl['log_has_timestamps'] else 'no '}timestamps, so the mismatch cannot be "
                   f"traced to particular files.")
        st = c["stale_snapshot"]["details"]
        lo, hi = st["changed_share_range"]
        out.append(f"- Stale snapshots: {len(st['stale'])}; between consecutive snapshots "
                   f"{lo:.1%}-{hi:.1%} of links changed band.")
        ub = c["unknown_band_share"]["details"]
        out.append(f"- Band outside 1-8 (published as 0 with no speed range): {_n(ub['rows'])} rows on "
                   f"{_n(ub['links'])} links; set to NULL in silver.")
        od = c["od_vs_tapin"]["details"]["by_month_day_type"]
        out.append("- OD trips vs stop tap-ins: " + "; ".join(
            f"{r['year_month']} {r['day_type'].lower()} {r['relative_diff']:.4%}" for r in od) + ".")
        ms = c["pv_stops_missing_from_master"]["details"]
        out.append(f"- {_n(ms['stops'])} stops in the passenger volumes are not in the 2026-09-26 stop list; "
                   f"they carry {_n(ms['tap_ins'])} tap-ins ({c['pv_stops_missing_from_master']['value']:.4%}).")
        qd = c["quarantine_share"]["details"]
        vol = {k: v for k, v in qd.get("volume_in_quarantined_rows", {}).items()}
        out.append(f"- Quarantined at ingest: {_n(qd['rows_quarantined'])} of {_n(qd['rows_read'])} rows"
                   + (f" ({', '.join(f'{k} {v}' for k, v in qd['reasons'].items())})" if qd["reasons"] else "")
                   + (f"; together they hold {', '.join(f'{_n(v)} {k}' for k, v in vol.items())}" if vol else "")
                   + ".")
        out.append("")

    rp = _load(res, "reproducibility.json")
    if rp:
        out += ["### Reproducibility", "",
                f"The batch pipeline ran twice from empty buckets (snapshots up to {rp['until']}), "
                f"{rp['run_seconds']['a']} s and {rp['run_seconds']['b']} s.", "",
                "| Gold table | Rows | Same Parquet bytes | Same content |", "|---|---|---|---|"]
        for t, v in rp["tables"].items():
            out.append(f"| {t} | {_n(v['rows'])} | {'yes' if v['file_sha256_equal'] else 'no'} | "
                       f"{'yes' if v['content_sha256_equal'] else 'no'} |")
        gm = _load(res, "gold_manifest.json")
        if gm:
            same = all(gm[t]["content_sha256"] == v["content_sha256"] for t, v in rp["tables"].items() if t in gm)
            files = _load(res, "speedband_files.json")
            backfill = sum(x["rows_new_in_bronze"] for x in files["snapshots"]) if files else None
            out += ["", f"The two runs built bronze speed bands from the snapshot files. In the main pipeline run the "
                        f"file backfill added {_n(backfill)} rows to the bronze written by the Kafka consumers, and "
                        f"its gold has the same content hashes as the two runs: {'yes' if same else 'no'}."]
        out.append("")

    tm = _load(res, "pipeline_timings.json")
    af = _load(res, "airflow/dag_run.json")
    if tm or af:
        out += ["### Batch pipeline runs", ""]
        if tm:
            out.append("- Without Airflow (`python -m lakehouse pipeline`): " +
                       ", ".join(f"{k} {v:g} s" for k, v in tm.items()) + f"; total {sum(tm.values()):.0f} s.")
        if af:
            def task(t):
                extra = ""
                if (t.get("attempts") or 1) > 1:
                    extra = (f", attempt {t['attempts']}; {t['attempts_terminated_by_scheduler']} earlier attempt "
                             f"terminated by the scheduler")
                return f"{t['task_id']} {t['state']} ({t['duration_s']} s{extra})"
            out.append(f"- Airflow DAG `{af['dag_id']}` run `{af['run_id']}` (snapshots up to {af['conf']['until']}): "
                       f"**{af['state']}** in {af['duration_s']} s. Tasks: " +
                       "; ".join(task(t) for t in af["tasks"]) + ".")
        out.append("- Durations were measured while other workloads shared the machine, so they vary a lot "
                   "between runs.")
        out.append("")

    mu = _load(res, "mutation.json")
    if mu:
        out += ["### Tests", "",
                f"- {mu['tests_passed']} pytest tests pass on the unmodified code: unit tests, the end-to-end "
                f"fixture run (whose dbt build runs {mu['dbt_tests']} dbt tests) and the fixture reproducibility "
                f"check.",
                f"- Mutation check: {mu['killed']}/{mu['total']} planted bugs killed "
                f"({mu['python']} in Python, {mu['sql']} in dbt SQL).", ""]
    return "\n".join(out).rstrip() + "\n"


def run(settings, update_readme: bool = False, check: bool = False) -> None:
    res = Path(settings.results_dir)
    text = build(res)
    readme = REPO / "README.md"
    r = readme.read_text(encoding="utf-8") if readme.exists() else ""
    if check:
        if START not in r or END not in r:
            sys.exit("README.md has no results block")
        current = r.split(START, 1)[1].split(END, 1)[0].strip()
        if current != text.strip():
            sys.exit("README.md results block differs from the results files; run `make summary`")
        print("README results block matches the results files")
        return
    (res / "SUMMARY.md").write_text("# Measured results\n\n" + text, encoding="utf-8")
    if update_readme and START in r and END in r:
        head, rest = r.split(START, 1)
        tail = rest.split(END, 1)[1]
        readme.write_text(f"{head}{START}\n{text}{END}{tail}", encoding="utf-8")
    print(text)
