    if prof:
        rec, srec = prof["reconciliation"], prof.get("speedband_reconciliation", [])
        dups = {d["dataset"]: d["duplicate_keys"] for d in prof["datasets"]}
        out += ["### Load validation", "",
                f"- Source-to-bronze reconciliation of the monthly files and the link file: "
                f"{sum(r['match'] for r in rec)}/{len(rec)} match. Source rows and volume sums come from a separate "
                f"Python pass over each raw file; the check is bronze rows + quarantined rows = source rows, and the "
                f"same for every volume column. Each file's SHA-256 is stored in the metadata of the Delta commit "
                f"that loaded it.",
                f"- Speed-band snapshots: {sum(r['match'] for r in srec)}/{len(srec)} files reconcile (source rows = "
                f"distinct links in bronze + quarantined rows + repeated links in the file).",
                "- Duplicate keys in bronze: " + ", ".join(f"{k} {v}" for k, v in dups.items()) + ".", ""]

    q = _load(res, "quality_report.json")
    if q:
        c = {x["check"]: x for x in q["checks"]}
        out += ["### Data-quality findings", "", "| Check | Status | Value | Threshold |", "|---|---|---|---|"]
        for x in q["checks"]:
            thr = x["threshold"]
            if isinstance(thr, dict):
                thr = ", ".join(f"{k} {v}" for k, v in thr.items())
            out.append(f"| {x['check']} | {x['status']} | {x['value']} | {thr} |")
        out.append("")
        cad = c["cadence_gap"]["details"]
        if cad.get("regular_minutes_min_median_max"):
            lo, med, hi = cad["regular_minutes_min_median_max"]
            out.append(f"- Sampling cadence: {cad['regular_intervals']} of {cad['intervals']} intervals were "
                       f"regular ({lo}-{hi} min, median {med} min).")
