"""Generate docs/CATALOG.md (data catalogue + lineage) from dbt's manifest.json and catalog.json.

Run after `python -m lakehouse dbt docs generate` (make docs). Reads the dbt target folder next to DUCKDB_PATH.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
from lakehouse import config  # noqa: E402


def main():
    s = config.load()
    target = Path(os.environ.get("DBT_TARGET_PATH", Path(s.warehouse).parent / "dbt_target"))
    man = json.loads((target / "manifest.json").read_text(encoding="utf-8"))
    cat_path = target / "catalog.json"
    cat = json.loads(cat_path.read_text(encoding="utf-8")) if cat_path.exists() else {"nodes": {}, "sources": {}}
    nodes = {k: v for k, v in man["nodes"].items() if v["resource_type"] in ("model", "seed")}
    tests = [v for v in man["nodes"].values() if v["resource_type"] == "test"]
    sources = man["sources"]

    def short(uid):
        n = man["nodes"].get(uid) or sources.get(uid)
        return f"bronze.{n['name']}" if n["resource_type"] == "source" else n["name"]

    tests_by = {}
    for t in tests:
        attached = t.get("attached_node")
        if attached:
            col = t.get("column_name") or "(model)"
            tests_by.setdefault(attached, {}).setdefault(col, []).append(
                t.get("test_metadata", {}).get("name") or t["name"])

    lines = ["# Data catalogue", "",
             "Generated by `tools/catalog.py` from the dbt manifest. Layers: bronze (sources written by the Python "
             "ingest), silver (cleaned, typed), gold (marts and features). Licence and provenance: "
             "[GOVERNANCE.md](GOVERNANCE.md).", "", "## Lineage", "", "```mermaid", "flowchart LR"]
    edges = set()
    for uid, n in nodes.items():
        if n["resource_type"] != "model":
            continue
        for dep in n["depends_on"]["nodes"]:
            if dep.startswith(("model.", "source.")):
                edges.add((short(dep), n["name"]))
    for a, b in sorted(edges):
        lines.append(f"  {a.replace('.', '_')}[{a}] --> {b}[{b}]")
    lines += ["```", ""]

    def section(title, items, is_source):
        out = [f"## {title}", ""]
        for uid, n in sorted(items, key=lambda x: x[1]["name"]):
            name = f"bronze.{n['name']}" if is_source else f"{n.get('schema', '')}.{n['name']}"
            out += [f"### {name}", "", " ".join((n.get("description") or "").split()), ""]
            meta = n.get("meta") or n.get("config", {}).get("meta") or {}
            if meta:
                out.append("Meta: " + ", ".join(f"{k}={v}" for k, v in meta.items() if k != "external_location"))
                out.append("")
            if not is_source:
                ups = [short(d) for d in n["depends_on"]["nodes"] if d.startswith(("model.", "source."))]
                if ups:
                    out += ["Upstream: " + ", ".join(sorted(ups)), ""]
            types = {c.lower(): v["type"] for c, v in
                     (cat["sources" if is_source else "nodes"].get(uid, {}).get("columns", {})).items()}
            cols = n.get("columns", {})
            if cols or types:
                out += ["| Column | Type | Description | Tests |", "|---|---|---|---|"]
                names = list(cols) + [c for c in types if c not in {k.lower() for k in cols}]
                for c in names:
                    d = " ".join((cols.get(c, {}).get("description") or "").split()).replace("|", "/")
                    t = ", ".join(sorted(set(tests_by.get(uid, {}).get(c, []))))
                    out.append(f"| {c} | {types.get(c.lower(), '')} | {d} | {t} |")
                model_tests = tests_by.get(uid, {}).get("(model)")
                if model_tests:
                    out += ["", "Model-level tests: " + ", ".join(sorted(set(model_tests)))]
                out.append("")
        return out

    lines += section("Bronze sources", sources.items(), True)
    lines += section("Silver and gold models", [(k, v) for k, v in nodes.items() if v["resource_type"] == "model"],
                     False)
    singular = sorted(t["name"] for t in tests if not t.get("test_metadata"))
    lines += ["## Singular tests", ""] + [f"- `{t}`" for t in singular] + [""]
    (REPO / "docs" / "CATALOG.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote docs/CATALOG.md:", len(nodes), "models/seeds,", len(sources), "sources,", len(tests), "tests")


if __name__ == "__main__":
    main()
